"""User test report (T16): turn the saved agree/disagree answers into the results tables.

Reads the `feedback` table from Supabase (or results/feedback_local.jsonl with --local), keeps the
latest answer per finding (a changed answer adds a row; the newest one counts), and writes
results/user_test_<name>.md with:
- Step 1 (naive list): share of findings the tester would NOT report as pathogenic.
- Step 2 (our second opinion): agreement with each verdict (Defensible / Contested / Declined).
- The overlap: for each naive-list variant, the tester's answer next to our verdict.
- Every typed reason, for matching against our flags by hand.

Read only. Never writes to Supabase.

Usage:
  python eval/user_test_report.py --name curator                # held-out sample, all sessions
  python eval/user_test_report.py --name curator  --session <id>
  python eval/user_test_report.py --name dev_check --sample dev --local
"""
import argparse
import json
import os
from pathlib import Path

import pandas as pd
from dotenv import load_dotenv

ROOT = Path(__file__).resolve().parent.parent
load_dotenv(ROOT / ".env")
RESULTS = ROOT / "results"


def load(local: bool) -> pd.DataFrame:
    if local:
        rows = [json.loads(l) for l in (RESULTS / "feedback_local.jsonl").read_text().splitlines() if l.strip()]
        return pd.DataFrame(rows)
    from supabase import create_client

    client = create_client(os.environ["SUPABASE_URL"], os.environ["SUPABASE_SERVICE_ROLE_KEY"])
    return pd.DataFrame(client.table("feedback").select("*").order("created_at").execute().data)


def pct(n: int, d: int) -> str:
    return f"{n}/{d} ({n / d:.0%})" if d else "0/0"


def table(df: pd.DataFrame) -> str:
    if not len(df):
        return "_No rows._"
    cell = lambda v: "" if pd.isna(v) else str(v).replace("|", "/").replace("\n", " ")
    lines = ["| " + " | ".join(df.columns) + " |", "|" + "---|" * len(df.columns)]
    lines += ["| " + " | ".join(cell(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--name", required=True, help="tester name, used in the output file name")
    ap.add_argument("--sample", default="heldout")
    ap.add_argument("--session", help="only this session_id")
    ap.add_argument("--local", action="store_true", help="read results/feedback_local.jsonl instead of Supabase")
    a = ap.parse_args()

    df = load(a.local)
    if df.empty:
        raise SystemExit("No feedback rows found.")
    df = df[df["sample"] == a.sample]
    if a.session:
        df = df[df["session_id"] == a.session]
    if df.empty:
        raise SystemExit(f"No rows for sample={a.sample!r}" + (f" session={a.session!r}" if a.session else ""))

    sessions = sorted(df["session_id"].unique())
    n_raw = len(df)
    df = (df.sort_values("created_at")
            .groupby(["session_id", "source", "variation_id"], as_index=False).last())
    base, sys_ = df[df["source"] == "baseline"], df[df["source"] == "system"]

    # Step 1: naive list. "disagree" = would not report it as pathogenic for this person.
    b_rej = int((base["answer"] == "disagree").sum())

    # Step 2: agreement with each verdict.
    by_verdict = (sys_.groupby("shown_verdict")["answer"]
                      .agg(shown="size", agree=lambda s: int((s == "agree").sum()),
                           disagree=lambda s: int((s == "disagree").sum()))
                      .reset_index().rename(columns={"shown_verdict": "verdict"}))
    s_agree = int((sys_["answer"] == "agree").sum())
    misses = sys_[(sys_["shown_verdict"] == "Defensible") & (sys_["answer"] == "disagree")]

    # Overlap: same variant judged on both lists.
    both = base.merge(sys_, on=["session_id", "variation_id"], suffixes=("_naive", "_system"))
    overlap = pd.DataFrame({
        "gene": both["gene_naive"],
        "variation_id": both["variation_id"],
        "ClinVar headline (naive list)": both["shown_verdict_naive"],
        "tester on naive list": both["answer_naive"].map({"agree": "would report", "disagree": "would not report"}),
        "our verdict": both["shown_verdict_system"],
        "tester on our verdict": both["answer_system"],
    })
    rejected_naive = both[both["answer_naive"] == "disagree"]
    caught = int(rejected_naive["shown_verdict_system"].isin(["Contested", "Declined"]).sum())

    reasons = pd.concat([
        base.assign(step="Step 1 naive"), sys_.assign(step="Step 2 ours"),
    ])[["step", "gene", "variation_id", "shown_verdict", "answer", "reason"]]
    reasons = reasons[reasons["reason"].fillna("").str.strip() != ""]
    reasons = reasons.assign(**{"matches our flag? (fill in)": ""})

    out = [
        f"# User test results: {a.name} ({a.sample} sample)",
        "",
        f"Generated by `eval/user_test_report.py` from {'local file' if a.local else 'Supabase'}. "
        f"{n_raw} saved rows, {len(df)} after keeping the latest answer per finding. "
        f"Sessions: {', '.join(s[:8] for s in sessions)}.",
        "",
        "## Headline numbers",
        "",
        f"- **Naive list (Step 1):** tester would not report {pct(b_rej, len(base))} of the findings as pathogenic.",
        f"- **Our second opinion (Step 2):** tester agreed with {pct(s_agree, len(sys_))} of our verdicts.",
        f"- **Naive findings the tester rejected that we had also marked Contested or Declined:** "
        f"{pct(caught, len(rejected_naive))}.",
        f"- **Misses (we said Defensible, tester disagreed):** {len(misses)}.",
        "",
        "## Step 2 agreement by verdict",
        "",
        table(by_verdict),
        "",
        "## Same variant, both lists",
        "",
        table(overlap),
        "",
        "## Reasons the tester typed",
        "",
        table(reasons),
        "",
        "## Notes from the call (fill in)",
        "",
        "- Spoken reasons not typed in:",
        "- Time per finding:",
        "- What confused him / what broke:",
        "- Quotes (with permission):",
        "",
    ]
    RESULTS.mkdir(exist_ok=True)
    path = RESULTS / f"user_test_{a.name}.md"
    path.write_text("\n".join(out), encoding="utf-8")
    print("\n".join(out[:12]))
    print(f"\nwritten: {path}")


if __name__ == "__main__":
    main()
